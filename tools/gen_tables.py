#!/usr/bin/env python3
"""Writes src/t9_tables.h: the sine table and the IMA ADPCM tables (no sample data: see mksamples.py)."""
import math
import pathlib

RIM_RPAR = 1 / (2 / 12e3 + 1 / 3.3e3)             # the rim's three summing resistors in parallel
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "t9_tables.h"

IMA_STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88,
            97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658,
            724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660,
            4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818,
            18500, 20350, 22385, 24623, 27086, 29794, 32767]
IMA_IDX = [-1, -1, -1, -1, 2, 4, 6, 8, -1, -1, -1, -1, 2, 4, 6, 8]


def diode(x, rs, rl, is_=2.5e-9, nvt=1.9 * 0.02585):
    """Anti-parallel silicon diode pair fed from x through rs, loaded by rl (the same solve as proto/t9f.c)."""
    u = max(-0.75, min(0.75, x * rl / (rs + rl)))
    for _ in range(60):
        f = (x - u) / rs - u / rl - 2 * is_ * math.sinh(u / nvt)
        df = -1 / rs - 1 / rl - 2 * is_ * math.cosh(u / nvt) / nvt
        du = max(-0.05, min(0.05, f / df))
        u -= du
        if abs(du) < 1e-12:
            break
    return u


def diode_table(rs, rl):
    """u(x) in Q15 volts: 257 points over 0..8 V (1/32 V), then 240 more over 8..128 V (1/2 V)."""
    xs = [i / 32 for i in range(257)] + [8 + i / 2 for i in range(1, 241)]
    return [round(32768 * diode(x, rs, rl)) for x in xs]


def rows(vals, per=12):
    return ",\n".join("\t" + ", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


def main():
    sine = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)]
    declick = [round(32767 * 0.5 * (1 + math.cos(math.pi * i / 96))) for i in range(96)]   # 1 -> 0 in 2 ms
    text = ("/* generated by gen_tables.py */\n#ifndef T9_TABLES_H\n#define T9_TABLES_H\n\n"
            f"static const int16_t t9_sine[257] = {{\n{rows(sine)}\n}};\n\n"
            f"static const int16_t t9_ima_step[89] = {{\n{rows(IMA_STEP)}\n}};\n\n"
            f"static const int8_t t9_ima_idx[16] = {{ {', '.join(map(str, IMA_IDX))} }};\n\n"
            f"/* diode-pair shapers, u(x): see diode_table() */\n"
            f"static const int16_t t9_diode_vco[497] = {{\n{rows(diode_table(10e3, 2.2e3))}\n}};\n\n"
            f"static const int16_t t9_diode_rim[497] = {{\n{rows(diode_table(RIM_RPAR, 12.68e3))}\n}};\n\n"
            f"#define T9_DECLICK_N 96\nstatic const int16_t t9_declick[96] = {{\n{rows(declick)}\n}};\n\n#endif\n")
    OUT.write_text(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
