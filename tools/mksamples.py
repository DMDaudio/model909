#!/usr/bin/env python3
"""Builds src/t9_samples.h from your own four 909 hits (closed hat, open hat, crash, ride): mono, 32 kHz, trimmed,
IMA ADPCM (4 bits a sample). Any WAV/AIFF ffmpeg reads will do.

The generated header (and the tweak and .syx built from it) carry your samples: keep them to yourself if the samples'
licence does not allow sharing them. src/t9_samples.h is in .gitignore.

    python3 tools/mksamples.py --ch CH.wav --oh OH.wav --crash Crash.wav --ride Ride.wav [--rate 32000]
"""
import argparse
import pathlib
import subprocess

import gen_tables

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "t9_samples.h"
NAMES = ("ch", "oh", "crash", "ride")                      # the C names, in the order t9.c uses them


def load(path, rate):
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", str(path), "-ac", "1", "-ar", str(rate), "-f", "s16le",
                          "-"], check=True, capture_output=True).stdout
    return [int.from_bytes(raw[i:i + 2], "little", signed=True) for i in range(0, len(raw), 2)]


def trim(x, rate):
    peak = max(abs(v) for v in x) or 1
    x = [round(v * 30000 / peak) for v in x]                 # same peak for all
    thr = 30000 * 10 ** (-66 / 20)
    end = max(i for i, v in enumerate(x) if abs(v) > thr) + 1
    start = next(i for i, v in enumerate(x) if abs(v) > 30000 * 10 ** (-40 / 20))
    start = max(0, start - rate // 4000)                     # keep 0.25 ms before the onset
    x = x[start:end]
    fade = min(len(x), rate // 100)                          # 10 ms fade out
    for i in range(fade):
        x[len(x) - fade + i] = round(x[len(x) - fade + i] * (fade - i) / fade)
    return x


def ima_encode(x):
    """Standard IMA ADPCM, first sample's prediction from 0. Low nibble first."""
    pred, idx, out = 0, 0, []
    for v in x:
        step = gen_tables.IMA_STEP[idx]
        d = v - pred
        code = 8 if d < 0 else 0
        d = abs(d)
        q, diff = 0, step >> 3
        if d >= step:
            q |= 4; d -= step; diff += step
        if d >= step >> 1:
            q |= 2; d -= step >> 1; diff += step >> 1
        if d >= step >> 2:
            q |= 1; diff += step >> 2
        pred = pred - diff if code else pred + diff
        pred = max(-32768, min(32767, pred))
        code |= q
        idx = max(0, min(88, idx + gen_tables.IMA_IDX[code]))
        out.append(code)
    if len(out) & 1:
        out.append(0)
    return bytes(out[i] | out[i + 1] << 4 for i in range(0, len(out), 2))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for n in NAMES:
        ap.add_argument(f"--{n}", required=True, type=pathlib.Path, help=f"the {n} sample (WAV, AIFF, ...)")
    ap.add_argument("--rate", type=int, default=32000)
    args = ap.parse_args()
    parts, total = [], 0
    for name in NAMES:
        x = trim(load(getattr(args, name), args.rate), args.rate)
        enc = ima_encode(x)
        total += len(enc)
        print(f"  {name}: {len(x)} samples ({len(x) / args.rate * 1000:.0f} ms), {len(enc)} bytes")
        body = ",\n".join("\t" + ", ".join(f"0x{b:02x}" for b in enc[i:i + 20]) for i in range(0, len(enc), 20))
        parts.append(f"static const uint8_t t9_s_{name}[{len(enc)}] = {{\n{body}\n}};\n"
                     f"#define T9_S_{name.upper()}_LEN {len(x)}u\n")
    OUT.write_text("/* generated by tools/mksamples.py from the builder's own samples: do not publish */\n"
                   "#ifndef T9_SAMPLES_H\n#define T9_SAMPLES_H\n\n"
                   f"#define T9_S_RATE {args.rate}\n\n" + "\n".join(parts) + "\n#endif\n")
    print(f"wrote {OUT}: {total} bytes of ADPCM")


if __name__ == "__main__":
    main()
