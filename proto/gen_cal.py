#!/usr/bin/env python3
"""Writes src/t9_cal.h: the analog voices' constants, from the prototypes' fits to the Mars hits (fits/*.json).

Each fitted circuit value becomes the firmware's fixed-point constant; the front-panel knobs are mapped in the
firmware (t9_analog.inc), with 64 at the fitted value where a knob scales one. The output gains put an accented hit
at about -1 dB below the voice's Q15 full scale.
"""
import json
import math
import pathlib

import numpy as np

import voices

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "t9_cal.h"
FS = 48000.0
FITS = {
    "bd": ("bd_BD_909_Clean_Long_A_01+BD_909_Tape_Medium_F_04+BD_909_Tube_Long_F_06", 0),
    "sd": ("sd_SD_909_Clean_E_01+SD_909_Clean_E_03+SD_909_Clean_E_10", 1),
    "lt": ("tom_Tom_Lo_909_Clean_01", 0),
    "mt": ("tom_Tom_Mid_909_Clean_03", 0),
    "ht": ("tom_Tom_Hi_909_Clean_04", 0),
    "rs": ("rs_Rim_909_Clean", 0),
    "hc": ("hc_Clap_909_Clean", 0),
}
PEAK = 29000                                            # an accented hit's peak, Q15


def fit(name):
    f, i = FITS[name]
    d = json.load(open(HERE / "fits" / f"{f}.json"))
    v = {"lt": "tom", "mt": "tom", "ht": "tom"}.get(name, name)
    knobs = voices.KNOBS[v] if "+" in f else ()
    p = {**voices.defaults(v), **{k: x for k, x in d["p"].items() if "@" not in k}}
    p.update({k: d["p"][f"{k}@{i}"] for k in knobs})
    return v, p


def q(x, bits):
    r = int(round(x * (1 << bits)))
    assert -(1 << 31) <= r < (1 << 31), (x, bits)
    return r


def kexp_(tau_s):                                        # exp(-1 / tau), Q31
    return min(q(math.exp(-1 / (tau_s * FS)), 31), (1 << 31) - 1)


def pole(hz):                                            # one-pole 1 - exp(-2 pi f / SR), Q31
    return q(1 - math.exp(-2 * math.pi * hz / FS), 31)


def rbj(kind, f0, qq):                                   # b0 b1 b2 a1 a2, Q30
    w = 2 * math.pi * f0 / FS
    al, c = math.sin(w) / (2 * qq), math.cos(w)
    a0 = 1 + al
    b = {"lp": ((1 - c) / 2, 1 - c, (1 - c) / 2), "hp": ((1 + c) / 2, -(1 + c), (1 + c) / 2),
         "bp": (al, 0, -al)}[kind]
    return [q(x / a0, 30) for x in (*b, -2 * c, 1 - al)]


def gain(v, p):
    """Q24 volts -> Q15 at PEAK for an accented hit: the firmware's out = q31(y, G), G = Q15 per volt x 128."""
    x = voices.render(v, n=1.0, **{**p, "accent": 1.0})
    return q(PEAK / np.abs(x).max() * 128 / (1 << 31), 31)


def shifted(k):                                          # a u32 numerator and the shift that brings it back
    sh = 0
    while k >= 2 ** 32:
        k /= 2
        sh += 1
    return int(k), sh


def main():
    L = ["/* generated by proto/gen_cal.py from proto/fits: do not edit */", "#ifndef T9_CAL_H", "#define T9_CAL_H", ""]
    d = lambda n, x, c="": L.append(f"#define {n} {x}" + (f"  /* {c} */" if c else ""))
    arr = lambda n, xs, t="s32": L.append(f"static const {t} {n}[{len(xs)}] = {{ {', '.join(str(x) for x in xs)} }};")

    # --- BD
    v, p = fit("bd")
    c8 = 0.33e-6 * p["c8"]
    ka, ka_sh = shifted(2 ** 31 / (c8 * FS))
    d("BD_FB_HZ16", round(p["fb"] * 16), f"{p['fb']:.2f} Hz")
    d("BD_DF_HZ16", round(p["df"] * 16), f"sweep {p['df']:.1f} Hz")
    d("BD_TP", q(p["tp"], 24), f"triangle peak {p['tp']:.2f} V")
    d("BD_TP_SINE", q(4.3, 24), "the drive where H3 nulls")
    d("BD_H2", q(p["h2"], 31))
    d("BD_CLICK", q(p["click"], 28)); d("BD_NZ", q(p["nz"], 28)); d("BD_BODY", q(p["body"], 28))
    d("BD_KA", f"{ka}u"); d("BD_KA_SH", ka_sh)
    d("BD_KB", q(1 / (470e3 * c8 * FS), 31))
    d("BD_HOLD", round(p["hold"] * FS), f"hold {p['hold'] * 1e3:.1f} ms")
    d("BD_THR", q(p["thr"], 24)); d("BD_VSTART", q(p["vstart"], 24)); d("BD_CLAMP", q(2.63, 24))
    d("BD_ACC", q(0.55, 30)); d("BD_PULSE", q(0.6, 24)); d("BD_PULSE_ACC", q(1.0, 24))
    d("BD_KENV2", kexp_(0.0007)); d("BD_DIF", pole(1 / (2 * math.pi * 3.3e-9 * 100e3)))
    d("BD_NHP", pole(26)); d("BD_NLP", pole(513)); d("BD_COUP", pole(10))
    d("BD_ATT0", q(0.18 / 0.42, 30)); d("BD_ATT1", q(1.0, 30))
    d("BD_OUT", gain(v, p), f"fit: tune {p['tune'] * 1e3:.1f} ms, decay {p['decay']:.2f}, attack {p['attack']:.2f}")
    arr("bd_sk", rbj("lp", 3720, 3.1))
    L.append("")

    # --- SD
    v, p = fit("sd")
    c67 = 0.47e-6
    ka4, ka4_sh = shifted(2 ** 31 / (c67 * FS))
    d("SD_F1_HZ16", round(p["f1"] * (1 + p["tune"]) * 16), f"VCO1 {p['f1'] * (1 + p['tune']):.1f} Hz")
    d("SD_BEND_HZ16", round(p["bend"] * 16)); d("SD_KB", kexp_(p["bend_t"]))
    d("SD_T1_16", round(p["t1"] * FS * 16)); d("SD_T2_16", round(p["t2"] * FS * 16))
    d("SD_KS", kexp_(0.001)); d("SD_R2", q(p["r2"], 29)); d("SD_TP", q(p["tp"], 24)); d("SD_L2", q(p["l2"], 30))
    d("SD_V4", q(p["v4"], 24)); d("SD_VEND", q(p["vend"], 24)); d("SD_ACC", q(0.55, 30))
    d("SD_HOLD4", round(p["hold4"] * FS)); d("SD_THR", q(p["thr"], 24))
    d("SD_KA4", f"{ka4}u"); d("SD_KA4_SH", ka4_sh); d("SD_KB4", q(1 / (220e3 * c67 * FS), 31))
    d("SD_LPF_HZ16", round(p["lpf"] * 16)); d("SD_LPK", q(1 / p["lpq"], 28))
    d("SD_NHP", pole(48)); d("SD_HPA", pole(1520)); d("SD_HPO", pole(7.2)); d("SD_K5", kexp_(1e-4))
    d("SD_SGAIN", q(p["sgain"], 24)); d("SD_BGAIN", q(p["bgain"], 24)); d("SD_DGAIN", q(p["dgain"], 24))
    d("SD_DSAT", q(p["dsat"], 24)); d("SD_DINV", q(12.2 / (2.2 * p["dsat"]), 24))
    sd_out = gain(v, p)
    d("SD_DOUT", q(12.2 / (2.2 * p["dsat"]) * p["dgain"] * sd_out / 2 ** 31, 31), "clip gain x drum level x output")
    d("SD_OUT", gain(v, p), f"fit (E_03): tone {p['tone']:.2f}, snappy {p['snappy']:.2f}")
    arr("sd_hpb", rbj("hp", 4050, 1.31))
    L.append("")

    # --- toms
    L += ["struct t9_tomcal {", "\tuint32_t f1_hz16, tfast16, t2min16, t2max16;",
          "\tint32_t vdd, vfast, vslow, ks, kod, od_m1, k1, kr, k3, r2, r3, tp, share, l1, l2, l3, nz, tick, acc, out, sh;",
          "\tint32_t nbp[5];", "};", "static const struct t9_tomcal tom_cal[3] = {"]
    for name in ("lt", "mt", "ht"):
        v, p = fit(name)
        f1 = p["f1"] * (1 + p["tune"])
        vals = [round(f1 * 16), round(p["tfast"] * FS * 16), round(p["t2min"] * FS * 16), round(p["t2max"] * FS * 16),
                q(1.705 * (1 + p["tune"]), 24), q(p["vfast"], 24), q(p["vslow"], 24), kexp_(p["tslow"]),
                kexp_(p["tod"]), q(p["od"] - 1, 24), kexp_(p["t1"]), q(1 / (p["rise2"] * FS), 31), kexp_(p["t3"]),
                q(p["r2"], 29), q(p["r3"], 29), q(p["tp"], 24), q(p["share"], 29), q(p["l1"], 28), q(p["l2"], 28),
                q(p["l3"], 28), q(p["nz"], 28), q(p["tick"], 28), q(0.45, 30), gain(v, p),
                q(p["l1"] * p["share"] / p["l2"], 28) if p["l2"] > 0 else 0]   # sh: VCO1's ENV2 share over l2
        L.append(f"\t{{ {', '.join(map(str, vals))}, {{ {', '.join(map(str, rbj('bp', p['nbf'], p['nbq'])))} }} }},"
                 f"  /* {name.upper()}: VCO1 {f1:.1f} Hz */")
    L += ["};"]
    d("TOM_KTICK", kexp_(0.00047))
    L.append("")

    # --- RS
    v, p = fit("rs")
    rpar = 1 / (2 / 12e3 + 1 / 3.3e3)
    arr("rs_f_hz16", [round(p[k] * 16) for k in ("f1", "f2", "f3")], "uint32_t")
    arr("rs_kq", [q(1 / p[k], 28) for k in ("q1", "q2", "q3")])
    arr("rs_g", [q(p[k], 24) for k in ("g1", "g2", "g3")], "uint32_t")
    d("RS_W12", q(rpar / p["r12"], 30)); d("RS_W3", f"{q(rpar / p['r3'], 30)}u")
    d("RS_TV16", round(p["vca_t"] * FS * 16)); d("RS_KICK", q(p["kick"], 24)); d("RS_KK", kexp_(p["kick_t"]))
    d("RS_RAIL", q(p["rail"], 24)); d("RS_ACC", q(0.55, 30)); d("RS_LP", pole(p["lpf"]))
    d("RS_OUT", 2 * gain(v, p)); arr("rs_hp", rbj("hp", p["hpf"], p["hpq"]))
    L.append("")

    # --- HC
    v, p = fit("hc")
    d("HC_BPF_HZ16", round(p["bpf"] * 16)); d("HC_BPK", f"{q(1 / p['bpq'], 28)}u")
    arr("hc_on", [round(p[k] * FS) for k in ("on2", "on3", "on4")], "uint32_t")
    d("HC_CTL16", round(p["ctl_t"] * FS * 16)); d("HC_LAST16", round(p["last_t"] * FS * 16))
    d("HC_TAIL16", round(p["tail"] * FS * 16)); d("HC_KR", kexp_(p["rise"]))
    d("HC_TILTMIX", f"{q(p['tiltmix'], 30)}u"); d("HC_ACC", q(0.7, 30))
    d("HC_BHP", pole(p["bhpf"])); d("HC_TILT", pole(p["tiltf"])); d("HC_TLP", pole(p["tlpf"]))
    d("HC_BGAIN", q(p["bgain"], 28)); d("HC_TGAIN", q(p["tgain"], 28)); d("HC_OUT", gain(v, p))
    D = p["depth"]
    arr("t9_hc_exp", [round(32767 * (math.exp(D * z / 256) - 1) / (math.exp(D) - 1)) for z in range(257)], "int16_t")
    L += ["", "#endif", ""]
    OUT.write_text("\n".join(L))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
